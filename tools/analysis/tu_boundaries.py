#!/usr/bin/env python3
"""Report conservative TU candidates from original function inventory and bytes.

Run after make extract. ROM offsets are offsets in the decompressed image,
not physical offsets in the compressed cartridge stream.
"""
import argparse
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
BASES = {'main': 0x8000F960, 'ovl_7DF8': 0x801ABB20}


def scan(root, image):
    original = json.loads((root / 'tools/progress/original-functions.json').read_text())
    functions = sorted((r for r in original.values() if r['area'] == image),
                       key=lambda r: int(r['vram'], 16))
    # Assembly supplies fresh labels/body ends for nonmatches; the persisted
    # original inventory supplies matched functions whose assembly disappears.
    assembly = {}
    for path in (root / 'asm/nonmatchings' / image).rglob('*.s'):
        source = path.read_text()
        label = re.search(r'^glabel\s+(\w+)', source, re.M)
        end = re.search(r'^endlabel\s+\w+', source, re.M)
        if label and end:
            insns = re.findall(r'/\*\s*[\dA-Fa-f]+\s+([\dA-Fa-f]{8})\s+[\dA-Fa-f]{8}\s*\*/', source[:end.start()])
            if insns:
                assembly[label[1]] = int(insns[-1], 16) + 4
    data = (root / f'build/segments/{image}.bin').read_bytes()
    base = BASES[image]
    rows = []
    for prev, following in zip(functions, functions[1:]):
        start, boundary = int(prev['vram'], 16), int(following['vram'], 16)
        if (boundary - base) % 16:
            continue
        end = assembly.get(prev['function'], start + int(prev['bytes']))
        # The declared body includes its delay slot and any legitimate nops.
        # Never infer a shorter body merely from the last nonzero word.
        if end > boundary or end < start + 8:
            continue
        terminal = struct.unpack_from('>I', data, end-base-8)[0]
        exits = (terminal == 0x03E00008 or terminal >> 26 == 2
                 or terminal >> 16 == 0x1000)
        padding = data[end-base:boundary-base]
        if any(padding) or len(padding) > 12:
            continue
        count = len(padding)//4
        # Explicit endlabels support padding after tail jumps as well as jr ra.
        # A zero-padding candidate needs terminal-control-flow evidence too.
        if not exits and (not count or prev['function'] not in assembly):
            continue
        rows.append(dict(image=image, vram=boundary, rom=boundary-base,
                         preceding=prev['function'], following=following['function'],
                         padding=count, confidence='definite' if count else 'possible'))
    return rows


def markdown(rows):
    out = ['# Translation unit boundary candidates', '',
           'Generated by `tools/analysis/tu_boundaries.py` after `make extract`. Original',
           'function starts and sizes come from the persisted assembly inventory; current',
           '`asm/nonmatchings/<image>/**/*.s` endlabels refine body ends. Extracted original',
           'image bytes cover matched C functions as well. Candidates follow an explicit',
           'endlabel or terminal return/jump and its delay slot, with only zero words',
           'after the declared body (at most three, the IDO alignment maximum),',
           'and start on a 16-byte boundary. A delay-slot nop is never counted as padding.',
           'Definite means observable padding, not proof of historical source provenance.',
           'Possible means an aligned terminal return/jump with no padding: this is weak evidence,',
           'and these rows are deliberately not used for splitting. Interior returns never',
           'shorten a declared body; nonzero trailing instructions are not padding.', '',
           'Both image bases are 16-byte aligned, so absolute VRAM alignment and alignment',
           'relative to main `0x8000F960` / overlay `0x801ABB20` are equivalent; these bytes',
           'cannot distinguish the conventions. ROM offsets below are **decompressed image**',
           'offsets (the YAML coordinate), not physical compressed-ROM offsets.', '']
    for image in BASES:
        out += [f'## {image}', '', '| Boundary VRAM | ROM offset | Preceding | Following | Padding words | Confidence |',
                '|---|---|---|---|---:|---|']
        for r in rows:
            if r['image'] == image:
                out.append(f"| 0x{r['vram']:08X} | 0x{r['rom']:X} | {r['preceding']} | {r['following']} | {r['padding']} | {r['confidence']} |")
        out.append('')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--json', action='store_true')
    args = parser.parse_args()
    rows = [r for image in BASES for r in scan(args.root, image)]
    print(json.dumps(rows, indent=2) if args.json else markdown(rows))


if __name__ == '__main__':
    main()
