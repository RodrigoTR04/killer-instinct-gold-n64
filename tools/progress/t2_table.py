#!/usr/bin/env python3
"""Rank every T2 function by its best committed draft.

For each function that docs/functions.csv lists as T2, every .c file under
tools/scratch/nonmatching that defines the function is scored with
tools/permuter/screen.py (run `make extract` first; the owning TU must still
contain the function's GLOBAL_ASM line). The lowest differing-word count wins.

Writes docs/t2_drafts.csv and docs/t2_drafts.md. Run inside the build toolbox:
  .venv/bin/python tools/progress/t2_table.py -j 8
"""
import argparse
import concurrent.futures
import csv
import importlib.util
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('screen', ROOT / 'tools/permuter/screen.py')
screen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(screen)

DEFINE = re.compile(r'^[A-Za-z_][^;{}\n]*\b(func_[0-9A-F]{8})\s*\([^;{]*\)\s*\{', re.M)
CONTEXTS = (dict(), dict(declarations=True), dict(prefix=True))


def candidates():
    found = {}
    for path in sorted((ROOT / 'tools/scratch/nonmatching').rglob('*.c')):
        names = set(DEFINE.findall(path.read_text(errors='replace')))
        names |= set(re.findall(r'func_[0-9A-F]{8}', path.name))  # K&R or oddly split headers
        for name in names:
            found.setdefault(name, []).append(path)
    return found


def score(function, draft):
    """Full TU if it compiles, else the best of declarations-only / TU prefix."""
    best = None
    for options in CONTEXTS:
        try:
            result = dict(screen.measure(function, draft, **options))
        except Exception as error:  # noqa: BLE001 - recorded in the table
            result = {'words': None, 'compiled': None, 'original': None, 'error': str(error)[:80]}
        result['context'] = next(iter(options), 'full')
        if result.get('error') or result.get('words') is None:
            best = best or result
            continue
        if best is None or best.get('words') is None or result['words'] < best['words']:
            best = result
        if not options:
            break  # full TU compiled; prefer it over weaker contexts
    return best


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('-j', type=int, default=6)
    args = parser.parse_args()
    rows = list(csv.reader((ROOT / 'docs/functions.csv').open()))[1:]
    t2 = {r[1]: r for r in rows if r[5] == 'T2'}
    found = candidates()
    jobs = [(f, p) for f in t2 for p in found.get(f, [])]
    with concurrent.futures.ThreadPoolExecutor(args.j) as pool:
        results = list(pool.map(lambda job: (job, score(*job)), jobs))
    best = {}
    for (function, draft), result in results:
        entry = dict(result, draft=str(draft.relative_to(ROOT)), candidates=len(found[function]))
        old = best.get(function)
        better = entry.get('words') is not None and (old is None or old.get('words') is None or entry['words'] < old['words'])
        if old is None or better:
            best[function] = entry
    out = []
    for function, row in t2.items():
        entry = best.get(function)
        out.append({
            'area': row[0], 'function': function, 'vram': row[2], 'bytes': int(row[4]),
            'words': entry['words'] if entry and entry.get('words') is not None else '',
            'compiled': (entry.get('compiled') or '') if entry else '',
            'context': entry.get('context', '') if entry else '',
            'draft': entry['draft'] if entry else '', 'drafts': entry['candidates'] if entry else 0,
            'error': ((entry.get('error') or '') if entry else 'no draft').replace('|', '/').replace('\n', ' '),
        })
    out.sort(key=lambda r: (r['words'] == '', r['words'] if r['words'] != '' else 0, -r['bytes']))
    fields = ['area', 'function', 'vram', 'bytes', 'words', 'compiled', 'context', 'draft', 'drafts', 'error']
    with (ROOT / 'docs/t2_drafts.csv').open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fields)
        writer.writeheader()
        writer.writerows(out)
    measured = [r for r in out if r['words'] != '']
    bands = [(0, 8), (9, 50), (51, 150), (151, 10**9)]
    lines = ['# T2 drafts ranked by closeness', '',
             'Generated by `tools/progress/t2_table.py` from `docs/functions.csv` and every draft under',
             '`tools/scratch/nonmatching`. **Words** = differing instruction words in the owning translation unit',
             '(relocation fields masked; a missing or extra word counts). **Context** says what was compiled:',
             'blank = full TU, `declarations` = TU declarations only, `prefix` = TU prefix only (a prefix or',
             'declarations count is not trustworthy until the declarations are reconciled). A draft with no',
             'count failed to compile standalone (see Error). Use `docs/OPPORTUNITIES.md` for what was tried.', '',
             '| Band (words) | Functions | Original bytes |', '|---|---:|---:|']
    for low, high in bands:
        rows_in = [r for r in measured if low <= r['words'] <= high]
        label = f'{low}–{high}' if high < 10**9 else f'>{low - 1}'
        lines.append(f"| {label} | {len(rows_in)} | {sum(r['bytes'] for r in rows_in):,} |")
    unmeasured = [r for r in out if r['words'] == '']
    lines.append(f"| not measurable | {len(unmeasured)} | {sum(r['bytes'] for r in unmeasured):,} |")
    lines += ['', f'{len(out)} T2 functions, {sum(r["bytes"] for r in out):,} B.', '',
              '| Function | Area | Bytes | Words | Context | Best draft | Error |', '|---|---|---:|---:|---|---|---|']
    for r in out:
        context = '' if r['context'] == 'full' else r['context']
        draft = f"`{r['draft']}`" if r['draft'] else ''
        lines.append(f"| `{r['function']}` | {r['area']} | {r['bytes']:,} | {r['words']} | {context} | {draft} | {r['error']} |")
    (ROOT / 'docs/t2_drafts.md').write_text('\n'.join(lines) + '\n')
    print(f'{len(out)} T2 functions, {len(measured)} measured')


if __name__ == '__main__':
    main()
